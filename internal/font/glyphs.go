package font

// glyphSpec is one glyph's source art: an ASCII '#'/'.' drawing with
// gridHeight rows of width columns each. The advance is always width plus
// one pixel of spacing.
type glyphSpec struct {
	r     rune
	width int
	rows  []string
}

func spec(r rune, width int, rows ...string) glyphSpec {
	return glyphSpec{r: r, width: width, rows: rows}
}

